TYPES = 0xFBA9B30
def tinfo(i):
    o = pe.rva_to_off(struct.unpack_from("<Q", d, TYPES + i*8)[0] - M.IMAGE_BASE)
    if o is None: return None
    return struct.unpack_from("<Q", d, o)[0], (struct.unpack_from("<I", d, o+8)[0] >> 16) & 0xff, struct.unpack_from("<I", d, o+8)[0] & 0xffff

POISON = 0x67676767
RD = (0xebb2e00, 0x20c6800)
def fields(nm):
    tdi = [i for i in range(md.type_count) if md.type(i)["name"] == nm][0]
    t = md.type(tdi); fo = md.sections["fields"][0]
    out = []
    for k in range(t["field_count"]):
        b = fo + (t["first_field"] + k)*12
        ni, fi, tok = struct.unpack_from("<iiI", md.data, b)
        x = tinfo(fi)
        out.append((md.string(ni) or "", x[1] if x else 0, x[2] if x else 0))
    return tdi, out

def scan(nm, req):
    tdi, fl = fields(nm)
    n = len(fl)
    mask = [1 if (f[0].startswith("%") or (f[2] & 0x10)) else 0 for f in fl]
    print("===", nm, "tdi", tdi, "n", n, "expected poison", sum(mask))
    hits = []
    o = RD[0]
    end = RD[0] + RD[1] - 4*n
    while o <= end:
        if struct.unpack_from("<i", d, o)[0] == POISON or mask[0] == 0:
            ok = True
            for k in range(n):
                v = struct.unpack_from("<i", d, o+4*k)[0]
                if (v == POISON) != bool(mask[k]):
                    ok = False; break
            if ok:
                hits.append(o)
                if len(hits) >= 40: break
        o += 4
    print("   mask hits", len(hits), [hex(x) for x in hits[:20]])
    # score hits by how many requested offsets appear at their metadata order positions
    for o in hits[:20]:
        vals = [struct.unpack_from("<i", d, o+4*k)[0] for k in range(n)]
        # monotonic check for real
        prev = -1; mono = True
        for v in vals:
            if v == POISON: continue
            if v < prev: mono = False; break
            prev = v
        found = [off for off in req if off in vals]
        print("      raw 0x%X rva 0x%X mon=%s req_hits=%d/%d first=%s" % (
            o, 0xebb5000 + (o - RD[0]), mono, len(found), len(req),
            [hex(v) for v in vals[:8]]))
    return tdi, fl

