"""Turn the community klass_rvas header into a compile-time seed table."""
from __future__ import annotations

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(HERE, "reference", "klass_rvas_26140533.hpp")
OUT = os.path.join(ROOT, "src", "generated", "TypeInfoSeeds.generated.h")

RE = re.compile(r"inline\s+static\s+constexpr\s+std::uintptr_t\s+(\w+)\s*=\s*0x([0-9A-Fa-f]+)\s*;")


def main():
    text = open(SRC, "r", encoding="utf-8", errors="ignore").read()
    # community spelling -> metadata class name
    aliases = {
        "ListComponent_Projectile": "ListComponent<Projectile>",
        "PlayerInventory_typenav": "PlayerInventory",
        "ConsoleSystem_Command": "Command",
        "ConVar_Graphics": "ConVar.Graphics",
        "ConVar_Admin": "ConVar.Admin",
        "TOD_SKY": "TOD_Sky",
    }
    seen = {}
    for name, rva in RE.findall(text):
        cls = aliases.get(name, name)
        for suffix in ("_TypeInfo", "_Static"):
            if cls.endswith(suffix):
                cls = cls[: -len(suffix)]
        seen[cls] = int(rva, 16)

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// AUTO-GENERATED by tools/gen_typeinfo_seeds.py - DO NOT EDIT\n")
        f.write("// Community klass_rvas seed for build 26140533.  The dumper still\n")
        f.write("// validates every slot at dump time before it is used.\n")
        f.write("#pragma once\n#include <cstdint>\n\n")
        f.write("namespace typeinfo_seeds\n{\n")
        f.write("    struct Seed { const char* klass; std::uint32_t rva; };\n")
        f.write("    inline constexpr Seed seeds[] = {\n")
        for cls, rva in sorted(seen.items()):
            f.write(f'        {{ "{cls}", 0x{rva:X} }},\n')
        f.write("    };\n")
        f.write("} // namespace typeinfo_seeds\n")
    print(f"[+] wrote {OUT} ({len(seen)} seeds)")


if __name__ == "__main__":
    sys.exit(main())
