"""Generate class -> IL2CPP TypeInfo usage index from global-metadata.dat.

A TypeInfo slot that has not been initialised yet contains a metadata usage
token:

    (kIl2CppMetadataUsageTypeInfo << 29) | (usageIndex << 1) | 1

For a normal class the usage index equals its TypeDefinition.byvalTypeIndex, so
we can compute the expected token from metadata without trusting any hardcoded
RVA.  The dumper scans the data sections for those tokens, which lets it resolve
RVAs that are still lazy when the dump runs.

This table is only a search hint: the resolver still reads the slot at dump time
and requires it to contain exactly the token it looked for.
"""
from __future__ import annotations

import os
import re
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DUMPER = os.path.join(ROOT, "src", "Dumper.h")
OUT = os.path.join(ROOT, "src", "generated", "TypeInfoTokens.generated.h")

META = r"C:\Program Files (x86)\Steam\steamapps\common\Rust\RustClient_Data\il2cpp_data\Metadata\global-metadata.dat"

# Build 26140533 metadata layout (verified against the live binary's slot
# tokens; all offsets are file offsets inside global-metadata.dat).
STRING_BASE = 0x2B5664
TYPE_TABLE = 0x3C91CEC
TYPE_STRIDE = 0x52
TYPE_COUNT = 0x822B

SET_RE = re.compile(
    r"static\s+const\s+std::set<std::string>\s+(exact|keys|dump)\s*=\s*\{(.*?)\};",
    re.S)
STR_RE = re.compile(r'"((?:[^"\\]|\\.)*)"')


def wanted_names():
    text = open(DUMPER, "r", encoding="utf-8", errors="ignore").read()
    names = set()
    for m in SET_RE.finditer(text):
        for s in STR_RE.findall(m.group(2)):
            names.add(s)
    return names


def load_types():
    d = open(META, "rb").read()
    if TYPE_TABLE + TYPE_STRIDE * 4 > len(d):
        raise SystemExit("metadata smaller than expected type table")
    names = {}
    for idx in range(TYPE_COUNT):
        off = TYPE_TABLE + idx * TYPE_STRIDE
        name_off, ns_off, byval = struct.unpack_from("<III", d, off)
        if name_off >= 0xFB165E:
            continue
        i = STRING_BASE + name_off
        j = d.find(b"\0", i, i + 160)
        if j < 0:
            continue
        name = d[i:j].decode("utf-8", "ignore")
        # first definition wins; duplicates only matter for the hint table
        names.setdefault(name, byval)
    return names


def main():
    types = load_types()
    names = sorted(wanted_names())
    found = []
    missing = []
    for name in names:
        if name in types:
            found.append((name, types[name]))
        else:
            missing.append(name)

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// AUTO-GENERATED by tools/gen_typeinfo_tokens.py - DO NOT EDIT\n")
        f.write("// class -> TypeDefinition.byvalTypeIndex, used to compute the lazy\n")
        f.write("// TypeInfo usage token.  Resolver still verifies the live slot.\n")
        f.write("#pragma once\n#include <cstdint>\n\n")
        f.write("namespace typeinfo_tokens\n{\n")
        f.write("    struct Token { const char* klass; std::uint32_t index; };\n")
        f.write("    inline constexpr Token tokens[] = {\n")
        for name, idx in found:
            f.write(f'        {{ "{name}", 0x{idx:X} }},\n')
        f.write("    };\n")
        f.write("} // namespace typeinfo_tokens\n")

    print(f"[+] wrote {OUT}: {len(found)} tokens, {len(missing)} names not in metadata")
    if missing:
        print("[!] no metadata type: " + ", ".join(missing[:25]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
